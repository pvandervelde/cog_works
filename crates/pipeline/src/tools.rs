/// A JSON Schema describing the structure of the expected LLM completion.
///
/// The LLM is asked to produce output conforming to this schema, and
/// `StructuredResponse::content` is validated against it before being
/// returned to the caller. Schema validation failures produce
/// [`LlmError::SchemaValidationFailed`].
///
/// See `docs/spec/interfaces/domain-traits.md` §OutputSchema.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct OutputSchema(serde_json::Value);

impl OutputSchema {
    /// Creates an [`OutputSchema`] from a raw JSON Schema value.
    ///
    /// Returns `None` if the value is not a JSON object (all valid JSON
    /// Schemas are objects at the root level).
    #[must_use]
    pub fn new(schema: serde_json::Value) -> Option<Self> {
        if schema.is_object() {
            Some(Self(schema))
        } else {
            None
        }
    }

    /// Returns the raw JSON Schema value.
    pub fn as_value(&self) -> &serde_json::Value {
        &self.0
    }
}

